export const additionalTcTriple = tcTripleRows.map(
  ([difficulty, text, blanks, answer, explanation], index) => {
    const rotated = blanks.map((choices, blankIndex) => (
      rotateChoices(choices, [answer[blankIndex]], (index * 2 + blankIndex) % choices.length)
    ))
    return {
      difficulty,
      text,
      blanks: rotated.map((blank) => blank.choices),
      answer: rotated.map((blank) => blank.answer[0]),
      explanation,
    }
  },
)


function placeCorrect(correct, distractors, position) {
  const choices = [...distractors]
  choices.splice(position, 0, correct)
  return { choices, answer: [position] }
}

function rotateChoices(choices, answer, offset) {
  const rotatedChoices = Array(choices.length)
  choices.forEach((choice, index) => {
    rotatedChoices[(index + offset) % choices.length] = choice
  })
  return {
    choices: rotatedChoices,
    answer: answer.map((index) => (index + offset) % choices.length),
  }
}

